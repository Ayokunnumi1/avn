#!/usr/bin/env node
/**
 * Generates PWA assets for all four apps: manifest, icons, service worker, offline page.
 * Run: node infrastructure/scripts/generate-pwa-assets.mjs   (outputs are committed)
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const sharp = createRequire(resolve(root, 'apps/api/package.json'))('sharp');

const APPS = [
  { dir: 'applicant-web', name: 'AVN — Address Verification', short: 'AVN', letter: 'U', color: '#0f766e', description: 'Verify your residential address securely.', start: '/dashboard' },
  { dir: 'verifier-web', name: 'AVN Agent', short: 'AVN Agent', letter: 'A', color: '#0b5e58', description: 'Earn by verifying addresses near you.', start: '/dashboard' },
  { dir: 'business-web', name: 'AVN Business', short: 'AVN Biz', letter: 'B', color: '#0f1b2d', description: 'Institutional address verification.', start: '/dashboard' },
  { dir: 'admin-web', name: 'AVN Admin', short: 'AVN Admin', letter: 'O', color: '#1f2a37', description: 'Platform operations centre.', start: '/dashboard' },
];
const VERSION = new Date().toISOString().slice(0, 10).replace(/-/g, '');

const iconSvg = (color, letter, maskable) => `<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 512 512">
<rect width="512" height="512" rx="${maskable ? 0 : 112}" fill="${color}"/>
<g transform="translate(256 236)"><path d="M0 -118 C 66 -118 112 -70 112 -10 C 112 64 0 150 0 150 C 0 150 -112 64 -112 -10 C -112 -70 -66 -118 0 -118 Z" fill="#fff" opacity=".96"/>
<path d="M-40 -8 l28 28 l56 -58" fill="none" stroke="${color}" stroke-width="26" stroke-linecap="round" stroke-linejoin="round"/></g>
<text x="256" y="470" text-anchor="middle" font-family="Arial, sans-serif" font-weight="800" font-size="54" fill="#fff" opacity=".85">AVN ${letter}</text></svg>`;

const sw = (app) => `/* AVN ${app.name} service worker — generated by infrastructure/scripts/generate-pwa-assets.mjs */
const CACHE = 'avn-${app.dir}-${VERSION}';
const PRECACHE = ['/offline.html', '/manifest.webmanifest', '/icons/icon-192.png', '/icons/icon-512.png'];

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('avn-${app.dir}-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') self.skipWaiting();
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  // Never cache API responses: they contain personal data, evidence and reports.
  if (url.pathname.startsWith('/api/')) return;
  // Hashed build assets are immutable: cache-first.
  if (url.pathname.startsWith('/_next/static/') || url.pathname.startsWith('/icons/')) {
    event.respondWith(caches.match(req).then((hit) => hit || fetch(req).then((res) => { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); return res; })));
    return;
  }
  // Pages: network-first with an offline fallback (pages are not cached).
  if (req.mode === 'navigate') {
    event.respondWith(fetch(req).catch(() => caches.match('/offline.html')));
  }
});

self.addEventListener('push', (event) => {
  let data = { title: '${app.short}', body: 'You have a new update.', url: '/notifications' };
  try { data = Object.assign(data, event.data ? event.data.json() : {}); } catch (e) {}
  // Lock-screen safe: payloads are generic by design.
  event.waitUntil(self.registration.showNotification(data.title, { body: data.body, icon: '/icons/icon-192.png', badge: '/icons/icon-192.png', data: { url: data.url } }));
});

self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  const target = (event.notification.data && event.notification.data.url) || '/';
  event.waitUntil(self.clients.matchAll({ type: 'window' }).then((list) => {
    for (const c of list) if ('focus' in c) { c.navigate(target); return c.focus(); }
    return self.clients.openWindow(target);
  }));
});
`;

const offline = (app) => `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Offline — ${app.name}</title>
<style>body{margin:0;font-family:system-ui,sans-serif;background:#f5f7f9;color:#0f1b2d;display:grid;place-items:center;min-height:100vh;padding:24px}
.c{background:#fff;border:1px solid #e2e8ee;border-radius:14px;padding:28px;max-width:420px;text-align:center}
.m{width:56px;height:56px;border-radius:14px;background:${app.color};color:#fff;display:grid;place-items:center;font-weight:800;margin:0 auto 12px}
button{margin-top:14px;background:${app.color};color:#fff;border:0;border-radius:8px;padding:12px 18px;font-weight:700;font-size:15px}</style></head>
<body><div class="c"><div class="m">AVN</div><h1 style="font-size:20px">You're offline</h1>
<p>${app.name} needs a connection for this page. Any drafts you saved are kept on this device and will sync when you're back online.</p>
<button onclick="location.reload()">Try again</button></div></body></html>`;

for (const app of APPS) {
  const pub = resolve(root, 'apps', app.dir, 'public');
  mkdirSync(resolve(pub, 'icons'), { recursive: true });
  for (const [size, maskable, file] of [[192, false, 'icon-192.png'], [512, false, 'icon-512.png'], [512, true, 'maskable-512.png'], [180, false, 'apple-touch-icon.png']]) {
    await sharp(Buffer.from(iconSvg(app.color, app.letter, maskable))).resize(size, size).png().toFile(resolve(pub, 'icons', file));
  }
  writeFileSync(resolve(pub, 'icons', 'icon.svg'), iconSvg(app.color, app.letter, false));
  writeFileSync(
    resolve(pub, 'manifest.webmanifest'),
    JSON.stringify(
      {
        name: app.name,
        short_name: app.short,
        description: app.description,
        id: `/${app.dir}`,
        start_url: app.start,
        scope: '/',
        display: 'standalone',
        orientation: app.dir === 'verifier-web' ? 'portrait' : 'any',
        background_color: '#f5f7f9',
        theme_color: app.color,
        icons: [
          { src: '/icons/icon-192.png', sizes: '192x192', type: 'image/png' },
          { src: '/icons/icon-512.png', sizes: '512x512', type: 'image/png' },
          { src: '/icons/maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
        ],
      },
      null,
      2,
    ),
  );
  writeFileSync(resolve(pub, 'sw.js'), sw(app));
  writeFileSync(resolve(pub, 'offline.html'), offline(app));
  console.log(`✓ ${app.dir}`);
}
